# components/su_dashboard_help.py
from nicegui import ui

def open_su_help_dialog(is_light: bool):
    """
    管理者（SU）専用の運営ヘルプ・操作ガイドダイアログを表示するコンポーネント。
    KPI分析、出席スコア付与、ランキング相性、防犯ログ解析、リアルタイムプレゼンス、
    DB構造まで、管理者機能の全11章すべてを網羅した完全版マニュアルです。
    """
    # テーマごとの配色設定
    dialog_bg = 'bg-slate-50 border-cyan-300' if is_light else 'bg-slate-900 border-cyan-500/30'
    text_main = 'text-slate-800' if is_light else 'text-white'
    text_sub = 'text-slate-500' if is_light else 'text-white/60'
    border_color = 'border-slate-200' if is_light else 'border-white/10'
    scroll_bg = 'bg-slate-100/50 border-slate-200' if is_light else 'bg-black/35 border-white/5'
    
    with ui.dialog().props('persistent=false') as dialog, ui.card().classes(f'w-[480px] max-w-full max-h-[85vh] {dialog_bg} {text_main} p-6 shadow-2xl rounded-2xl flex flex-col no-wrap'):
        
        # ヘッダー（タイトル）
        with ui.row().classes(f'w-full justify-between items-center border-b {border_color} pb-3 mb-2 shrink-0'):
            with ui.row().classes('items-center gap-2'):
                ui.icon('security', size='sm', color='cyan-400')
                ui.label('日々、彩り。 運営・管理者ガイド【完全版】').classes('text-sm font-black text-white tracking-wider')
            ui.button(icon='close', on_click=dialog.close).props(f'flat round size=sm color={"grey-8" if is_light else "white"}')
        
        # UI構築用インナーヘルパー関数
        def su_section(title):
            ui.label(title).classes('text-xs font-black text-cyan-500 mt-5 mb-1.5 w-full border-b border-cyan-500/10 pb-1')
        def su_item(title):
            ui.label(title).classes('text-[11px] font-extrabold text-amber-500 dark:text-amber-300 mt-3 mb-1')
        def su_body(text):
            ui.label(text).classes(f'{text_sub} text-[11px] leading-relaxed pl-2 whitespace-pre-line')

        # スクロールエリア（長文でもはみ出さず、スマホでも快適に読めるように保護）
        with ui.scroll_area().classes(f'w-full flex-grow border rounded-xl p-4 {scroll_bg} clean-scroll'):
            with ui.column().classes('w-full gap-2.5 pb-6'):
                
                ui.label('日々、彩り。 運営者向け 総合運用ドキュメント').classes('text-xs font-bold text-center w-full pb-2 border-b border-white/5')
                ui.label('本マニュアルは、コミュニティの和を守り、Hibiを安全かつ円滑に管理・運用していくための全機能の手順書です。他者への公開は厳禁です。').classes(f'text-[10px] {text_sub} leading-relaxed text-center w-full whitespace-pre-line')

                # -------------------------------------------------------------
                # 1. 運営基本方針
                # -------------------------------------------------------------
                su_section('1. コミュニティの基本方針')
                su_body(
                    '本サービスは完全招待・事前承認制のクローズドコミュニティです。\n'
                    '管理者の主たる役割は以下の3点です。\n'
                    '・治安の維持：ハラスメント、荒らし、情報の外部漏洩、なりすましの早期対処。\n'
                    '・入国の管理：信頼できるメンバーのみを迎え入れるための厳格な審査。\n'
                    '・運用の補助：メンバーからの要望・質問・通報への迅速なサポート。'
                )

                # -------------------------------------------------------------
                # 2. 治安維持・緊急対応システム
                # -------------------------------------------------------------
                su_section('2. 治安維持 ＆ 緊急対応')
                
                su_item('🚦 2-1. NG審議（保留）フロー')
                su_body(
                    '・システムがNGワードを自動検知した投稿やコメントは、タイムラインに即公開されず「審議待ち」に入ります。\n'
                    '・承認：内容が健全・無害である場合は「承認」を押してタイムラインへ公開します。\n'
                    '・否認：規約に抵触する場合は「否認」を押して論理削除します（投稿者に自動で非開示通知が送信されます）。\n'
                    '・処理結果は監査ログに「承認/否認」の履歴として自動で残ります。'
                )
                
                su_item('📩 2-2. サポートチケット対応')
                su_body(
                    '・ユーザーからの要望、質問、荒らし通報などが届くセクションです。\n'
                    '・「至急（荒らしの通報等）」は真っ赤なカードで最上位にアラート表示されますので、最優先で対処してください。\n'
                    '・対応中・解決済みにステータスを切り替えると、自動で相手に通知が送られます。'
                )
                
                su_item('🚫 2-3. 悪質アカウントの即時BAN（利用停止）')
                su_body(
                    '・荒らし、漏洩、性別の偽装申告等が発覚した場合、「ユーザー管理」または「稼働状態」の詳細画面から対象者のステータスを「BAN」に変更します。\n'
                    '・BANされたアカウントは即座にセッションが強制切断され、以降システムへのログインが永久に拒絶されます。'
                )

                # -------------------------------------------------------------
                # 3. イベント出席 ＆ 貢献度（スコア・レベル）
                # -------------------------------------------------------------
                su_section('3. イベント出席 ＆ 貢献度システム')
                
                su_item('📅 3-1. イベント参加者へのスコア一括付与')
                su_body(
                    '・「イベント出席管理」から対象イベントを選択し、「参加者リストを開く」を押します。\n'
                    '・ダイアログに表示される参加予定者のうち、実際に出席した人のスイッチをONにします。\n'
                    '・ONに切り替わると、瞬時に「イベント出席スコア（+20pt）」が付与され、ユーザーの「レベル（LV.1〜MAX）」が自動更新されます。\n'
                    '・誤ってONにした場合でも、OFFに戻せば出席データは安全に抹消され、スコアも自動減算されます。'
                )
                
                su_item('🏆 3-2. 貢献度トップランキング')
                su_body(
                    '・メンバー全員の獲得ポイント（イベント出席：20pt、コメント：5pt、いいね：2pt、ログイン：1ptなど）をDBから自動集計し、上位10名をリアルタイムにランキングします。\n'
                    '・運営陣（Master/SubMasterなど）のスコアが一般メンバーと競合しないよう、管理者は自動的にレベル表示が「✨ LV: ??（シークレット）」に補正されます。'
                )
                
                su_item('🤝 3-3. 相性分析（よく一緒に飲む人）')
                su_body(
                    '・各ユーザーの「よく一緒に飲む仲間（出席が重なっているメンバー）」を、データベースを基に自動的に分析し、ランキング下部に最大3名までアバターアイコンとして自動描画します。\n'
                    '・アバターにホバーすると「メンバー名（一緒に出席した回数）」がツールチップ表示され、メンバー間の交友関係を把握できます。'
                )

                # -------------------------------------------------------------
                # 4. リアルタイム稼働状態（プレゼンス監視システム）
                # -------------------------------------------------------------
                su_section('4. リアルタイム稼働状態（プレゼンス）')
                
                su_item('🟢 4-1. 物理的一元化メモリプレゼンスの仕組み')
                su_body(
                    '・システムを開いている稼働中のメンバーをリアルタイムで直接監視する機能です。\n'
                    '・メンバーが画面のどこかを触ったり、チャットを開いた瞬間、その最後のアクティブなアクセス時刻がサーバー側の一元化物理メモリ（sys._active_users_presence）にミリ秒単位で即時記録されます。\n'
                    '・直近45秒以内にアクセスがあった場合は「🟢 オンライン」、それ以上経過しているか、画面を閉じた・別タブにバックグラウンドした場合は自動的に「⚪ オフライン（バッジ内に×表示）」へと3秒以内に全管理者に同期・反映されます。'
                )
                
                su_item('🔌 4-2. スマホ・バックグラウンド切断時の安全弁（フリーズ防止設計）')
                su_body(
                    '・スマートフォンのLINEアプリ内ブラウザやスリープ機能などにより、一時的にWebSocket接続が切断された場合であっても、画面が「強制切断エラー（真っ白になってシステムが完全にフリーズするバグ）」を防止するための専用の安全弁が搭載されています。\n'
                    '・切断中である間、稼働バッジの監視エンジンは対象のスマホへの状態配信（リフレッシュパケット）を安全にスキップ（自動保留）して待機し、再接続された瞬間に自動で同期をシームレスに再開します。'
                )
                
                su_item('🚪 4-3. ログアウト時の即時破棄')
                su_body(
                    '・メンバーが「ログアウト」ボタンを押して離脱した場合は、45秒のタイムアウト待機を挟まず、その瞬間にメモリ上からアクティブデータを物理破棄します。これによって、他者が管理画面を見た際にオフライン状態が一瞬で（遅延0で）正確に反映されます。'
                )

                # -------------------------------------------------------------
                # 5. 入国管理 ＆ 招待履歴
                # -------------------------------------------------------------
                su_section('5. 入国管理 ＆ 招待履歴')
                
                su_item('⏳ 5-1. 承認待ちユーザーの入国許可')
                su_body(
                    '・新規メンバーが登録申請を行うと、ここに表示されます。信頼できる関係者であることを確認したら「承認する」を押してください。\n'
                    '・承認されると一般メンバーとして本システムをフル利用できるようになります。'
                )
                
                su_item('🤝 5-2. 招待履歴追跡')
                su_body(
                    '・「招待履歴」から誰が誰を招待したかの招待経路テーブルが閲覧できます。\n'
                    '・荒らしアカウントが発生した際、そのアカウントが「誰の招待コードを経由して入国したか」を辿ることで、招待元のアカウントの特定・芋づる式のBANなどの対策が可能です。'
                )

                # -------------------------------------------------------------
                # 6. システム運用記録 ＆ 防犯ログ
                # -------------------------------------------------------------
                su_section('6. 運用記録 ＆ 防犯ログ')
                
                su_item('📋 6-1. 防犯アクセスログ監査')
                su_body(
                    '・不正アクセスや荒らしアカウントを特定するため、接続元IP・地域・端末情報（UA）を記録しています。\n'
                    '・不審な海外IPや、不自然な同時接続などがないかセキュリティ監視に役立ててください。'
                )
                
                su_item('📝 6-2. 運営メモ')
                su_body(
                    '・管理者間のみで共有されるメモ板です。引き継ぎ、BANした経緯の記録、イベントの役割分担などにご活用ください。'
                )

                # -------------------------------------------------------------
                # 7. アナリティクス（KPI）
                # -------------------------------------------------------------
                su_section('7. アナリティクス（KPI）の見方')
                su_body(
                    '・アクティブ推移（過去7日間）：システム全体のアクセス数（PV）の推移を折れ線グラフで表示します。活用の目安にしてください。\n'
                    '・ページ別アクセス内訳（本日分）：本日どのページが特に人気を集めているか（タイムライン、イベント、チャット、AIスナックなど）を棒グラフで表示します。'
                )

                # -------------------------------------------------------------
                # 8. データベース設計概要
                # -------------------------------------------------------------
                su_section('8. データベース設計（主要スキーマ仕様）')
                
                su_item('🗄️ profiles テーブル')
                su_body(
                    '・id (uuid/PK) : ユーザーの固有ID。外部連携時はOAuthのUIDにマッピング\n'
                    '・name (text) : ニックネーム（重複不可、表示名）\n'
                    '・gender (smallint) : 性別（0:回答しない, 1:男性, 2:女性, 3:その他）\n'
                    '・role (text) : ユーザー権限（superuser / member）\n'
                    '・status (text) : 会員ステータス（pending:承認待ち, approved:承認済, banned:停止中）\n'
                    '・total_score (numeric) : 累計スコア（イベント出席 ＋ 各種アクションで算出）'
                )
                
                su_item('🗄️ timeline_posts テーブル')
                su_body(
                    '・id (uuid/PK) : 投稿の固有ID\n'
                    '・user_id (uuid/FK) : 投稿者のユーザーID\n'
                    '・content (text) : 投稿の本文\n'
                    '・status (text) : 投稿のステータス（approved / pending:保留審査中）\n'
                    '・likes_count (integer) : いいね（❤️）の総数'
                )
                
                su_item('🗄️ events テーブル')
                su_body(
                    '・id (uuid/PK) : イベントの固有ID\n'
                    '・title (text) : イベントのタイトル\n'
                    '・event_date (text) : 開催日時（YYYY-MM-DD HH:MM フォーマット）\n'
                    '・participant_ids (text[]) : 参加表明したユーザーIDの配列\n'
                    '・details (uuid/FK) : 連携された実名チャットルームのID'
                )

        # 閉じるボタン
        btn_close_bg = 'bg-slate-300 hover:bg-slate-400 text-slate-800' if is_light else 'bg-slate-800 hover:bg-slate-700 text-white'
        ui.button('閉じる', on_click=dialog.close).classes(f'w-full mt-4 {btn_close_bg} py-2 rounded-xl text-xs font-bold shrink-0')
        
    dialog.open()